// Input is an already selected scalar attribute value, never source HTML. The
// caller still bounds its length, rejects malformed literal-quote helper shapes,
// and escapes decoded text at the eventual attribute insertion boundary.
export function decodeNativeEntities(value: string): string {
    return value.replace(/&(?:#(?:[xX][0-9a-fA-F]+|[0-9]+)|[A-Za-z][A-Za-z0-9_]*);?/g, token => {
        if (token[1] !== "#") {
            const key = token.slice(1);
            const bare = key.endsWith(";") ? key.slice(0, -1) : key;
            const code = Object.hasOwn(NAMES, key) ? NAMES[key] :
                Object.hasOwn(NAMES, bare) ? NAMES[bare] : undefined;
            return code === undefined ? token : String.fromCodePoint(code);
        }
        const digits = token.slice(2).replace(/;$/, "");
        const hex = digits[0] === "x" || digits[0] === "X";
        // Number overflow remains literal. Leading zeroes don't make a valid
        // small codepoint overflow, and C1 controls are not Windows-1252 mapped.
        const code = Number.parseInt(hex ? digits.slice(1) : digits, hex ? 16 : 10);
        if (!Number.isSafeInteger(code) || code === 0 || code > 0x10ffff ||
            code === 0xfffe || code === 0xffff) return token;
        return String.fromCodePoint((code >= 0xd800 && code <= 0xdfff) ||
            (code >= 0xfdd0 && code <= 0xfdef) || (code & 0xffff) >= 0xfffe ? 0xfffd : code);
    });
}
