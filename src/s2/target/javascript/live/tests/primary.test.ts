import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import test from "node:test";
import mysql from "mysql2/promise";
import { sql } from "kysely";
import { PrimaryDatabases, primarySources, primaryTransport, type SqlRow } from "../data/primary";
import { SnapshotError } from "../data/errors";
import type { ConfiguredDatabase, ConfiguredDatabaseSource } from "../startup-types";

function source(id: string, database: string, roles: Record<string, number> = {}): ConfiguredDatabaseSource {
    return {id, database, roles, host: null, port: null,
        socketPath: "/var/run/mysqld/mysqld.sock", user: "root", password: ""};
}
function config(sources: ConfiguredDatabaseSource[]): ConfiguredDatabase {
    return {defaultDatabase: "livejournal", sources, clusters: [7, 19], clusterPairActive: {"19": "b"}};
}

test("source role selection uses master identity and only active weighted primaries", () => {
    const value = config([
        source("master", "custom_global", {def_reader: 1}),
        source("arbitrary-id", "custom_seven", {cluster7: 0.5}),
        source("another-id", "custom_seven", {cluster7: 8}),
        source("inactive", "custom_a", {cluster19a: 100}),
        source("active", "custom_b", {cluster19b: 3}),
        source("reader", "wrong", {cluster7slave: 100, def_reader: 100}),
        source("_internal", "wrong", {cluster7: 100}),
    ]);
    assert.deepEqual(primarySources(value).map(s => s.id), ["master"]);
    assert.deepEqual(primarySources(value, 7).map(s => s.id), ["arbitrary-id", "another-id"]);
    assert.deepEqual(primarySources(value, 19).map(s => s.id), ["active"]);
    assert.throws(() => primarySources(value, 1), SnapshotError);
    assert.throws(() => primarySources({...value, sources: value.sources.slice(1)}), SnapshotError);
    assert.throws(() => primarySources({...value, clusterPairActive: {"19": "c" as "a"}}, 19), SnapshotError);
    assert.throws(() => primarySources({...value, sources: [...value.sources, value.sources[0]!]}), SnapshotError);
    assert.throws(() => primarySources(config([source("master", "x"),
        source("bad", "x", {cluster7: Infinity})]), 7), SnapshotError);
});

test("native localhost uses an explicit socket; TCP hosts ignore socket facts", {
    skip: process.env.S2_PRIMARY_FIXTURE !== "1",
}, () => {
    const native = JSON.parse(execFileSync("perl", ["live/tests/primary-endpoint.pl"], {
        encoding: "utf8", timeout: 10000,
    })) as {host: string; socket: boolean; authentication: boolean}[];
    assert.deepEqual(native, [
        {host: "127.0.0.1", socket: false, authentication: true},
        {host: "localhost", socket: true, authentication: false},
        {host: "LOCALHOST", socket: false, authentication: true},
    ]);
    const socketPath = "/tmp/explicit-configured-socket";
    for (const row of native) {
        assert.deepEqual(primaryTransport({host: row.host, port: 1234, socketPath}),
            row.socket ? {socketPath} : {host: row.host, port: 1234});
    }
    assert.deepEqual(primaryTransport({host: null, port: 1234, socketPath}), {socketPath});
    assert.deepEqual(primaryTransport({host: "", port: 1234, socketPath}), {socketPath});
    assert.deepEqual(primaryTransport({host: "db.example", port: null, socketPath}), {host: "db.example"});
    for (const host of [null, "", "localhost"]) {
        assert.throws(() => primaryTransport({host, port: 3306, socketPath: null}),
            (error: unknown) => error instanceof SnapshotError && error.kind === "unsupported");
    }
});

test("own isolated MySQL schemas: privileged credential still reads only, active pair, snapshot and safe failure", {
    skip: process.env.S2_PRIMARY_FIXTURE !== "1",
}, async () => {
    assert.equal(process.env.LJHOME, "/workspaces/dreamwidth");
    const admin = await mysql.createConnection({socketPath: "/var/run/mysqld/mysqld.sock", user: "root"});
    const prefix = "s6_primary_" + randomBytes(8).toString("hex");
    const schemas = [prefix + "_global", prefix + "_seven", prefix + "_b"];
    const created: string[] = [];
    let databases: PrimaryDatabases | undefined;
    try {
        for (let index = 0; index < schemas.length; index++) {
            const schema = schemas[index]!;
            // Only names generated by this test can be created or dropped.
            assert.match(schema, /^s6_primary_[a-f0-9]{16}_(global|seven|b)$/);
            await admin.query(`CREATE DATABASE \`${schema}\``);
            created.push(schema);
            await admin.query(`CREATE TABLE \`${schema}\`.probe (id INT PRIMARY KEY, value INT) ENGINE=InnoDB`);
            await admin.query(`INSERT INTO \`${schema}\`.probe VALUES (1, ?)`, [index + 1]);
        }
        const value = config([source("master", schemas[0]!), source("seven", schemas[1]!, {cluster7: 1}),
            source("b", schemas[2]!, {cluster19b: 1}), source("inactive", schemas[1]!, {cluster19a: 100})]);
        databases = PrimaryDatabases.create(value);
        const read = (cluster: number | undefined) => databases!.snapshot(cluster, ["probe"], async connection =>
            (await sql<SqlRow>`SELECT value FROM probe WHERE id = 1`.execute(connection)).rows[0]!.value);
        assert.equal(await read(undefined), 1);
        assert.equal(await read(7), 2);
        assert.equal(await read(19), 3);
        await assert.rejects(databases.snapshot(7, ["probe"], async connection => {
            await sql`UPDATE probe SET value = 99 WHERE id = 1`.execute(connection);
        }), (error: unknown) => error instanceof SnapshotError && error.kind === "unavailable");
        assert.equal(await read(7), 2);
        await databases.snapshot(7, ["probe"], async connection => {
            assert.equal((await sql<SqlRow>`SELECT value FROM probe WHERE id = 1`.execute(connection)).rows[0]!.value, 2);
            await admin.query(`UPDATE \`${schemas[1]}\`.probe SET value = 4 WHERE id = 1`);
            assert.equal((await sql<SqlRow>`SELECT value FROM probe WHERE id = 1`.execute(connection)).rows[0]!.value, 2);
        });
        assert.equal(await read(7), 4);
        // A caller mutation cannot retarget the private configuration snapshot.
        (value.sources[1] as {database: string}).database = schemas[2]!;
        assert.equal(await read(7), 4);
        await admin.query(`CREATE TABLE \`${schemas[1]}\`.nontransactional (id INT) ENGINE=MyISAM`);
        await assert.rejects(databases.snapshot(7, ["nontransactional"], async () => 1),
            (error: unknown) => error instanceof SnapshotError && error.kind === "unsupported");
        await assert.rejects(databases.snapshot(7, ["missing"], async () => 1), SnapshotError);
        const failure = PrimaryDatabases.create(config([
            {...source("master", schemas[0]!), host: "127.0.0.1", port: 1, socketPath: null,
                password: "SECRET_SENTINEL_NOT_IN_ERRORS"},
            source("seven", schemas[1]!, {cluster7: 1}), source("b", schemas[2]!, {cluster19b: 1}),
        ]));
        try {
            await assert.rejects(failure.snapshot(undefined, ["probe"], async () => 1), (error: unknown) => {
                assert.ok(error instanceof SnapshotError);
                assert.equal(error.message, "Journal data unavailable");
                assert.equal(error.kind, "unavailable");
                assert.ok(!JSON.stringify(error).includes("SECRET_SENTINEL"));
                return true;
            });
        } finally { await failure.close(); }
    } finally {
        await databases?.close();
        for (const schema of created.reverse()) await admin.query(`DROP DATABASE \`${schema}\``);
        await admin.end();
    }
});
